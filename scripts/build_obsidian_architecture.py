def backend_files() -> list[Path]:
    out = []
    for p in sorted(BACKEND.rglob("*.py")):
        r = p.relative_to(BACKEND).as_posix()
        if r.startswith(("tests/", "alembic/", ".venv/")) or "__pycache__" in r or "site-packages" in r:
            continue
        if p.name == "__init__.py":
            continue
        out.append(p)
    return out


def module_name(p: Path) -> str:
    return p.relative_to(BACKEND).with_suffix("").as_posix().replace("/", ".")


def backend_note_name(mod: str) -> str:
    for prefix, group in BACKEND_GROUPS.items():
        if mod == prefix or mod.startswith(prefix + "."):
            return group
    return mod


def resolve_py_import(importer: str, node: ast.AST, known: set[str]) -> set[str]:
    """Return the backend module names an import statement refers to."""
    found: set[str] = set()
    pkg_parts = importer.split(".")[:-1]
    if isinstance(node, ast.Import):
        for a in node.names:
            name = a.name
            while name:
                if name in known:
                    found.add(name)
                    break
                name = name.rpartition(".")[0]
    elif isinstance(node, ast.ImportFrom):
        if node.level:
            base = pkg_parts[: len(pkg_parts) - (node.level - 1)] if node.level > 1 else pkg_parts
            mod = ".".join(base + ([node.module] if node.module else []))
        else:
            mod = node.module or ""
        if mod in known:
            found.add(mod)
        for a in node.names:
            cand = f"{mod}.{a.name}" if mod else a.name
            if cand in known:
                found.add(cand)
        if not found and mod:
            m = mod
            while m:
                if m in known:
                    found.add(m)
                    break
                m = m.rpartition(".")[0]
    return found


def parse_models() -> tuple[dict[str, str], dict[str, str], dict[str, int]]:
    """class name -> table name, table -> class docstring, table -> line."""
    tree = ast.parse((BACKEND / "models.py").read_text(encoding="utf-8"))
    cls_to_table, table_doc, table_line = {}, {}, {}
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        for stmt in node.body:
            if (
                isinstance(stmt, ast.Assign)
                and any(isinstance(t, ast.Name) and t.id == "__tablename__" for t in stmt.targets)
                and isinstance(stmt.value, ast.Constant)
            ):
                cls_to_table[node.name] = stmt.value.value
                table_doc[stmt.value.value] = first_paragraph(ast.get_docstring(node), 300)
                table_line[stmt.value.value] = node.lineno
    return cls_to_table, table_doc, table_line


def table_note(t: str) -> str:
    return f"{t} (table)"


ROUTE_DECOS = {"get", "post", "put", "patch", "delete", "api_route"}


def router_info(tree: ast.Module) -> tuple[dict[str, str], list[tuple[str, str, str]]]:
    """Router variable -> prefix, and (method, router_var, path) routes."""
    prefixes: dict[str, str] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Call):
            fn = node.value.func
            if (isinstance(fn, ast.Name) and fn.id == "APIRouter") or (isinstance(fn, ast.Attribute) and fn.attr == "APIRouter"):
                prefix = ""
                for kw in node.value.keywords:
                    if kw.arg == "prefix" and isinstance(kw.value, ast.Constant):
                        prefix = kw.value.value
                for t in node.targets:
                    if isinstance(t, ast.Name):
                        prefixes[t.id] = prefix
    routes = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            for d in node.decorator_list:
                if (
                    isinstance(d, ast.Call)
                    and isinstance(d.func, ast.Attribute)
                    and d.func.attr in ROUTE_DECOS
                    and isinstance(d.func.value, ast.Name)
                    and d.args
                    and isinstance(d.args[0], ast.Constant)
                    and isinstance(d.args[0].value, str)
                ):
                    routes.append((d.func.attr.upper(), d.func.value.id, d.args[0].value))
    return prefixes, routes


def build_backend(notes: dict[str, Note], cls_to_table: dict[str, str]) -> dict[str, list[tuple[str, str]]]:
    files = backend_files()
    known = {module_name(p) for p in files}
    router_routes: dict[str, list[tuple[str, str]]] = {}

    for p in files:
        mod = module_name(p)
        name = backend_note_name(mod)
        src_text = p.read_text(encoding="utf-8", errors="replace")
        try:
            tree = ast.parse(src_text)
        except SyntaxError:
            continue
        is_router = mod.startswith("routers.")
        is_group = name != mod
        if name not in notes:
            group_prefix = next((k for k in BACKEND_GROUPS if mod == k or mod.startswith(k + ".")), None)
            notes[name] = Note(
                name=name,
                layer="backend",
                kind="router" if is_router else ("folder" if is_group else "module"),
                key=group_prefix or mod,
                source=(f"backend/{group_prefix.replace('.', '/')}/" if is_group else rel(p)),
            )
        n = notes[name]
        n.lines += src_text.count("\n") + 1
        doc = first_paragraph(ast.get_docstring(tree))
        if is_group:
            n.sections["Files"].append(f"`{rel(p)}`" + (f": {doc}" if doc else ""))
        else:
            n.summary = doc

        models_aliases = set()
        for node in ast.walk(tree):
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                for target in resolve_py_import(mod, node, known):
                    n.link("Imports", backend_note_name(target))
                if isinstance(node, ast.ImportFrom) and node.module == "models" and not node.level:
                    for a in node.names:
                        if a.name in cls_to_table:
                            n.link("Tables used", table_note(cls_to_table[a.name]))
                if isinstance(node, ast.Import):
                    for a in node.names:
                        if a.name == "models":
                            models_aliases.add(a.asname or "models")
            elif isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name) and node.value.id in models_aliases:
                if node.attr in cls_to_table:
                    n.link("Tables used", table_note(cls_to_table[node.attr]))

        if is_router:
            prefixes, routes = router_info(tree)
            full = [(m, "/api" + prefixes.get(var, "") + path) for m, var, path in routes]
            router_routes[name] = full
            if prefixes:
                pf = sorted(set(prefixes.values()))
                n.facts.append("API prefix: " + ", ".join(f"`/api{x}`" if x else "`/api` (no prefix)" for x in pf))
            uniq = sorted(set(full), key=lambda x: (x[1], x[0]))
            for m, path in uniq[:80]:
                n.sections["Endpoints"].append(f"`{m} {path}`")
            if len(uniq) > 80:
                n.sections["Endpoints"].append(f"… and {len(uniq) - 80} more")

    # Nested routers: routers/settings.py does `router.include_router(account_router)`,
    # so routers.account is served under /api/settings/account/...
    for host in list(router_routes):
        host_path = BACKEND / (host.replace(".", "/") + ".py")
        tree = ast.parse(host_path.read_text(encoding="utf-8"))
        alias_to_mod = {}
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and (node.module or "").startswith("routers."):
                for a in node.names:
                    alias_to_mod[a.asname or a.name] = node.module
        host_prefixes, _ = router_info(tree)
        for node in ast.walk(tree):
            if (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                    and node.func.attr == "include_router" and node.args
                    and isinstance(node.args[0], ast.Name) and node.args[0].id in alias_to_mod
                    and isinstance(node.func.value, ast.Name)):
                child = alias_to_mod[node.args[0].id]
                prefix = host_prefixes.get(node.func.value.id, "")
                if child in router_routes and prefix:
                    router_routes[child] = [(m, p.replace("/api", "/api" + prefix, 1)) for m, p in router_routes[child]]
                    notes[child].facts.append(f"Mounted inside: `{host}` (served under `/api{prefix}`)")
                    notes[child].sections["Endpoints"] = [
                        f"`{m} {p}`" for m, p in sorted(set(router_routes[child]), key=lambda x: (x[1], x[0]))]
                    notes[host].link("Mounts routers", child)

    main = notes.get("main")
    if main:
        for name, nt in notes.items():
            if nt.kind == "router":
                main.link("Mounts routers", name)
    return router_routes


def build_db(notes: dict[str, Note], cls_to_table, table_doc, table_line) -> None:
    for cls, t in cls_to_table.items():
        notes[table_note(t)] = Note(
            name=table_note(t),
            layer="db",
            kind="table",
            key=f"table:{t}",
            source=f"backend/models.py:{table_line[t]}",
            summary=table_doc.get(t, ""),
            facts=[f"SQLAlchemy model: `{cls}`"],
        )
        notes[table_note(t)].link("Defined in", "models")

    versions = sorted((BACKEND / "alembic" / "versions").glob("*.py"))
    tables = set(cls_to_table.values())
    for p in versions:
        text = p.read_text(encoding="utf-8", errors="replace")
        tree = ast.parse(text)
        rev = down = None
        for node in tree.body:
            target = value = None
            if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
                target, value = node.target.id, node.value
            elif isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
                target, value = node.targets[0].id, node.value
            if target in ("revision", "down_revision") and isinstance(value, ast.Constant):
                if target == "revision":
                    rev = value.value
                else:
                    down = value.value
        rev = rev or p.stem
        n = Note(
            name=rev,
            layer="db",
            kind="migration",
            key=f"migration:{rev}",
            source=rel(p),
            summary=first_paragraph(ast.get_docstring(tree)),
            lines=text.count("\n") + 1,
        )
        if down:
            n.link("Previous migration", down)
        for t in sorted(tables):
            if re.search(rf"""["']{re.escape(t)}["']""", text):
                n.link("Tables touched", table_note(t))
        notes[rev] = n

    db_text = (BACKEND / "database.py").read_text(encoding="utf-8")
    m = re.search(r"EXPECTED_ALEMBIC_HEAD\s*(?::[^=]+)?=\s*['\"]([^'\"]+)['\"]", db_text)
    if m and "database" in notes:
        notes["database"].facts.append(f"`EXPECTED_ALEMBIC_HEAD` = `{m.group(1)}`")
        notes["database"].link("Expected Alembic head", m.group(1))


