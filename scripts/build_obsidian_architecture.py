def frontend_files() -> list[Path]:
    out = []
    for p in sorted(FRONTEND_SRC.rglob("*")):
        if p.suffix not in (".js", ".jsx") or ".test." in p.name:
            continue
        r = p.relative_to(FRONTEND_SRC).as_posix()
        if r.startswith("test/"):
            continue
        out.append(p)
    return out


def fe_key(p: Path) -> str:
    return p.relative_to(FRONTEND_SRC).with_suffix("").as_posix()


def fe_group(p: Path) -> str | None:
    parts = p.relative_to(FRONTEND_SRC).parts
    if len(parts) == 1:
        return None
    if parts[0] == "components":
        return None if len(parts) == 2 else f"components/{parts[1]}"
    if parts[0] in FRONTEND_INDIVIDUAL_DIRS:
        return None
    return parts[0]


def fe_note_name(p: Path) -> str:
    g = fe_group(p)
    if g:
        return g.replace("/", ".") + " (folder)"
    k = fe_key(p)
    if "/" not in k:
        return f"src.{k}"
    return k.replace("/", ".")


def lead_comment(text: str) -> str:
    m = LEAD_COMMENT.match(text)
    if not m:
        return ""
    raw = m.group(1) if m.group(1) is not None else m.group(2)
    lines = [re.sub(r"^\s*(\*|//)\s?", "", ln).strip() for ln in raw.splitlines()]
    return first_paragraph("\n".join(lines).strip(), 300)


def match_router(path: str, router_routes: dict[str, list[tuple[str, str]]]) -> str | None:
    """Best router for a frontend API path (``/billing/status``)."""
    want = [s for s in ("/api" + path).split("/") if s]
    best, best_score = None, 0.0
    for router, routes in router_routes.items():
        for _m, rp in routes:
            segs = [s for s in rp.split("/") if s]
            score = 0
            for a, b in zip(want, segs):
                if a == b or b.startswith("{"):
                    score += 1
                else:
                    break
            exact = score == len(segs) == len(want)
            s = score + (0.5 if exact else 0)
            if score >= 2 and s > best_score:
                best, best_score = router, s
    return best


def build_frontend(notes: dict[str, Note], router_routes) -> None:
    files = frontend_files()
    by_key = {fe_key(p): p for p in files}
    src_resolved = FRONTEND_SRC.resolve()

    def resolve(spec: str, importer: Path) -> Path | None:
        if spec == "@edition-manifest":
            return by_key.get("editions/cloud")
        if not spec.startswith("."):
            return None
        base = (importer.parent / spec).resolve()
        try:
            k = base.relative_to(src_resolved).as_posix()
        except ValueError:
            return None
        k = re.sub(r"\.(jsx?|css)$", "", k)
        return by_key.get(k) or by_key.get(k + "/index")

    api_path = FRONTEND_SRC / "api.js"
    api_fn_router: dict[str, str] = {}
    api_text = api_path.read_text(encoding="utf-8")
    exports = list(EXPORT_CONST.finditer(api_text))
    for i, m in enumerate(exports):
        body = api_text[m.end(): exports[i + 1].start() if i + 1 < len(exports) else len(api_text)]
        call = API_CALL.search(body)
        if call:
            r = match_router(call.group(2), router_routes)
            if r:
                api_fn_router[m.group(1)] = r

    for p in files:
        name = fe_note_name(p)
        text = p.read_text(encoding="utf-8", errors="replace")
        group = fe_group(p)
        key = fe_key(p)
        if name not in notes:
            parts = p.relative_to(FRONTEND_SRC).parts
            kind = "folder" if group else (
                "page" if parts[0] == "pages" else
                "component" if parts[0] == "components" else
                "hook" if parts[0] == "hooks" else
                "lib" if parts[0] in ("lib", "auth", "editions") else "file"
            )
            notes[name] = Note(
                name=name,
                layer="frontend",
                kind=kind,
                key=group or (key if "/" in key else f"src/{key}"),
                source=(f"frontend/src/{group}/" if group else rel(p)),
            )
        n = notes[name]
        n.lines += text.count("\n") + 1
        comment = lead_comment(text)
        if group:
            n.sections["Files"].append(f"`{rel(p)}`" + (f": {comment}" if comment else ""))
        else:
            n.summary = comment
            ex = EXPORT_CONST.findall(text)
            if ex and p != api_path:
                n.facts.append("Exports: " + ", ".join(f"`{e}`" for e in ex[:12]) + (" …" if len(ex) > 12 else ""))

        for spec in JS_IMPORT.findall(text):
            target = resolve(spec, p)
            if target is not None:
                n.link("Imports", fe_note_name(target))
        for names, spec in JS_NAMED.findall(text):
            if resolve(spec, p) == api_path:
                for nm in names.split(","):
                    nm = nm.strip().split(" as ")[0].strip()
                    if nm in api_fn_router:
                        n.link("Calls backend", api_fn_router[nm])
        for _m, path in API_CALL.findall(text):
            r = match_router(path, router_routes)
            if r:
                n.link("Calls backend", r)
        for path in FETCH_CALL.findall(text):
            r = match_router(path, router_routes)
            if r:
                n.link("Calls backend", r)

    api_note = notes.get("src.api")
    if api_note:
        api_note.facts.append(f"API helpers: {len(exports)} exported, {len(api_fn_router)} mapped to a router")
        api_note.summary = api_note.summary or (
            "Axios client: injects `portfolio_id`, `X-Workspace-ID` and `X-CSRF-Token` "
            "(see PORTFOLIO_AGNOSTIC_PREFIXES); almost every backend call goes through here."
        )


