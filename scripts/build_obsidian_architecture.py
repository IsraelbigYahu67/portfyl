SECTION_ORDER = ["Mounts routers", "Imports", "Calls backend", "Tables used", "Defined in", "Previous migration",
                 "Tables touched", "Expected Alembic head", "Mentions code", "Mentioned in docs"]


def hubs_for(n: Note) -> list[str]:
    hubs: list[str] = []
    for rx, hub in HUB_RULES:
        if re.search(rx, n.key) and hub not in hubs:
            hubs.append(hub)
    if n.layer == "db" and "Database and migrations" not in hubs:
        hubs.append("Database and migrations")
    if not hubs:
        hubs.append(LAYER_HUB[n.layer])
    return hubs


def slug(h: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", h.lower()).strip("-")


def render(n: Note, existing: set[str]) -> str:
    hubs = hubs_for(n)
    tags = list(dict.fromkeys([f"arch/{n.layer}", f"arch/{n.kind}"] + [f"hub/{slug(h)}" for h in hubs]))
    out = [
        "---",
        f"type: {n.kind}",
        f"layer: {n.layer}",
        "tags: [" + ", ".join(tags) + "]",
        f'source: "{n.source}"',
        "generated: true",
        "---",
        "",
        f"# {n.name}",
        "",
        GENERATED_BANNER,
        "",
    ]
    if n.summary:
        out += [safe_text(n.summary), ""]
    out.append("**Hub:** " + " · ".join(f"[[{h}]]" for h in hubs))
    out.append(f"**Source:** `{n.source}`" + (f" ({n.lines} lines)" if n.lines else ""))
    for f in n.facts:
        head, _, tail = f.partition(":")
        out.append(f"**{head}:**{tail}" if tail else f)
    out.append("")
    for title, items in n.sections.items():
        if items:
            out.append(f"## {title}")
            out += [f"- {safe_text(i)}" for i in items]
            out.append("")
    for title in SECTION_ORDER:
        targets = sorted(t for t in n.links.get(title, ()) if t in existing or title == "Mentioned in docs")
        if targets:
            out.append(f"## {title}")
            out += [f"- [[{t}]]" for t in targets]
            out.append("")
    return "\n".join(out).rstrip() + "\n"


# ==========================================================================
# Vault report: resolve every link the way Obsidian does
# ==========================================================================

WIKILINK = re.compile(r"(?<!!)\[\[([^\]|#^]+)(?:[#^][^\]|]*)?(?:\|[^\]]*)?\]\]")
MDLINK = re.compile(r"(?<!!)\[[^\]]*\]\(([^)\s]+?\.md)(?:#[^)]*)?\)")


def vault_report(exclude: tuple[str, ...] = ()) -> dict:
    """Notes, edges, orphans and unresolved links across the whole docs/ vault."""
    notes = [p for p in DOCS.rglob("*.md") if ".obsidian" not in p.parts]
    rel_paths = {p: p.relative_to(DOCS).with_suffix("").as_posix() for p in notes}
    by_path = {v.lower(): k for k, v in rel_paths.items()}
    by_base: dict[str, list[Path]] = defaultdict(list)
    for p in notes:
        by_base[p.stem.lower()].append(p)

    def resolve(target: str, src: Path) -> Path | None:
        t = target.strip().removesuffix(".md").lower()
        if t in by_path:
            return by_path[t]
        cands = by_base.get(t.rsplit("/", 1)[-1], [])
        if "/" in t:
            cands = [c for c in cands if rel_paths[c].lower().endswith(t)]
        if not cands:
            return None
        # Obsidian prefers the closest file; any match is "resolved" for the graph.
        return sorted(cands, key=lambda c: (c.parent != src.parent, len(c.parts)))[0]

    def excluded(p: Path) -> bool:
        return rel_paths[p].startswith(exclude)

    edges: set[tuple[Path, Path]] = set()
    unresolved: dict[str, set[str]] = defaultdict(set)
    for p in notes:
        text = p.read_text(encoding="utf-8", errors="replace")
        text = re.sub(r"^(```|~~~).*?^\1", "", text, flags=re.M | re.S)
        text = re.sub(r"`[^`\n]*`", "", text)  # inline code is not a link
        for target in WIKILINK.findall(text):
            dst = resolve(target, p)
            if dst is None:
                unresolved[rel_paths[p]].add(target)
            elif dst != p:
                edges.add((p, dst))
        for target in MDLINK.findall(text):
            if "://" in target:
                continue
            dst = (p.parent / target).resolve()
            if dst.exists() and dst in rel_paths:
                if dst != p:
                    edges.add((p, dst))
            elif dst.exists():
                pass
            else:
                unresolved[rel_paths[p]].add(target)
    shown = [p for p in notes if not excluded(p)]
    connected = set()
    for a, b in edges:
        if not excluded(a) and not excluded(b):
            connected.update((a, b))
    orphans = sorted(rel_paths[p] for p in shown if p not in connected)
    return {
        "notes": len(shown),
        "edges": sum(1 for a, b in edges if not excluded(a) and not excluded(b)),
        "orphans": orphans,
        "unresolved": {k: sorted(v) for k, v in sorted(unresolved.items()) if not k.startswith(exclude)},
    }


# Legal/compliance drafts use [[DOPLNIT: …]]-style reviewer placeholders, not links.
PLACEHOLDER = re.compile(r"^(DOPLNIT|OV\S*IT|PR\S*VN\S*K|ROZHODNOUT|LAWYER|DECIDE|VERIFY|TODO)\b|^\W*$")


def print_report() -> None:
    for label, excl in (("whole vault", ()), ("graph view (filter -path:design/stitch)", ("design/stitch",))):
        r = vault_report(excl)
        real = {k: [t for t in v if not PLACEHOLDER.match(t)] for k, v in r["unresolved"].items()}
        real = {k: v for k, v in real.items() if v}
        placeholders = sum(len(v) for v in r["unresolved"].values()) - sum(len(v) for v in real.values())
        print(f"[{label}] notes: {r['notes']}  links: {r['edges']}  orphans: {len(r['orphans'])}  "
              f"unresolved links: {sum(len(v) for v in real.values())} "
              f"(+{placeholders} reviewer placeholders like [[DOPLNIT]])")
        for o in r["orphans"]:
            print(f"    orphan: {o}")
        if excl == ():
            for k, v in real.items():
                print(f"    unresolved in {k}: {', '.join(v[:6])}{' …' if len(v) > 6 else ''}")


class GenerationError(RuntimeError):
    pass


def build_notes() -> tuple[dict[str, Note], int]:
    notes: dict[str, Note] = {}
    cls_to_table, table_doc, table_line = parse_models()
    router_routes = build_backend(notes, cls_to_table)
    build_db(notes, cls_to_table, table_doc, table_line)
    build_frontend(notes, router_routes)
    extra = build_ops(notes)
    ndocs = scan_docs(notes, extra)

    lower: dict[str, list[str]] = defaultdict(list)
    for nm in notes:
        lower[nm.lower()].append(nm)
        if BAD_SUFFIX.search(nm):
            raise GenerationError(f"note name ends like a file extension: {nm}")
    dupes = [v for v in lower.values() if len(v) > 1]
    if dupes:
        raise GenerationError(f"duplicate note names: {dupes}")
    return notes, ndocs


def generate(verbose: bool = True) -> dict[Path, str]:
    """Render every generated file in memory: {absolute path: content}."""
    notes, ndocs = build_notes()
    existing = set(notes)
    hub_names = sorted({h for n in notes.values() for h in hubs_for(n)})
    missing_hubs = [h for h in hub_names if not (HUBS_DIR / f"{h}.md").exists()]

    counts: dict[str, int] = defaultdict(int)
    for n in notes.values():
        counts[f"{n.layer}/{n.kind}"] += 1
    if verbose:
        print(f"notes: {len(notes)}  docs scanned: {ndocs}")
        for k in sorted(counts):
            print(f"  {k}: {counts[k]}")
    if missing_hubs:
        print("hub notes not written yet:", ", ".join(missing_hubs), file=sys.stderr)

    files = {OUT / n.layer / f"{n.name}.md": render(n, existing) for n in notes.values()}
    manifest = {
        "generator": "scripts/build_obsidian_architecture.py",
        "notes": len(notes),
        "hubs": hub_names,
        "by_kind": dict(sorted(counts.items())),
    }
    files[OUT / "_manifest.json"] = json.dumps(manifest, indent=2) + "\n"
    return files


def _on_disk() -> set[Path]:
    if not OUT.exists():
        return set()
    return {p for p in OUT.rglob("*") if p.is_file() and (p.suffix == ".md" or p.name == "_manifest.json")}


def _read(p: Path) -> str | None:
    try:
        return p.read_text(encoding="utf-8")
    except OSError:
        return None


def diff_generated(files: dict[Path, str]) -> dict[str, list[Path]]:
    """Compare rendered files with docs/architecture/generated/ on disk."""
    disk = _on_disk()
    return {
        "missing": sorted(p for p in files if p not in disk),
        "stale": sorted(p for p in files if p in disk and _read(p) != files[p]),
        "extra": sorted(disk - set(files)),
    }


def write_generated(verbose: bool = False) -> int:
    """Bring generated/ up to date, touching only files that change. Returns the number changed."""
    files = generate(verbose=verbose)
    d = diff_generated(files)
    for p in d["missing"] + d["stale"]:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(files[p], encoding="utf-8")
    for p in d["extra"]:
        p.unlink()
    for folder in sorted((p for p in OUT.rglob("*") if p.is_dir()), reverse=True):
        if not any(folder.iterdir()):
            folder.rmdir()
    return sum(len(v) for v in d.values())


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate Obsidian architecture notes for Portfyl.")
    ap.add_argument("--check", action="store_true", help="print stats only, write nothing")
    ap.add_argument("--verify", action="store_true",
                    help="exit 1 if docs/architecture/generated/ is out of date; write nothing")
    ap.add_argument("--report", action="store_true", help="only report notes/orphans/unresolved links in docs/")
    args = ap.parse_args()
    if args.report:
        print_report()
        return 0
    try:
        if args.check:
            generate()
            return 0
        if args.verify:
            d = diff_generated(generate(verbose=False))
            bad = sum(len(v) for v in d.values())
            for kind, paths in d.items():
                for p in paths:
                    print(f"  {kind}: {rel(p)}")
            if bad:
                print(f"architecture graph is out of date ({bad} files); "
                      "run: python scripts/build_obsidian_architecture.py")
                return 1
            print("architecture graph is up to date")
            return 0
        changed = write_generated(verbose=True)
    except GenerationError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    print(f"updated {changed} files in {rel(OUT)}/" if changed else f"{rel(OUT)}/ already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
