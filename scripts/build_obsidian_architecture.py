def ops_note_name(r: str) -> str:
    if r == "Dockerfile":
        return "Dockerfile"
    path = r.lstrip(".")
    stem, dot, ext = path.rpartition(".")
    if dot and "/" not in ext and stem:
        return stem.replace("/", ".") + f" ({ext})"
    return path.replace("/", ".")


OPS_SKIP = {"package-lock.json"}
OPS_GROUPS = {
    "deploy/cloudflare/": "Cloudflare Worker (beta proxy) and its wrangler config, deployed with wrangler.",
}


def build_ops(notes: dict[str, Note]) -> list[tuple[Note, Path]]:
    candidates = [ROOT / "Dockerfile", ROOT / "start.bat", ROOT / "CLAUDE.md", ROOT / "DESIGN.md",
                  ROOT / "README.md", ROOT / "frontend" / "vite.config.js",
                  BACKEND / "alembic.ini", BACKEND / "tests" / "conftest.py",
                  BACKEND / "tests" / "postgres" / "conftest.py"]
    candidates += sorted((ROOT / ".github" / "workflows").glob("*.y*ml"))
    candidates += sorted(p for p in (ROOT / "deploy").rglob("*")
                         if p.is_file() and "node_modules" not in p.parts and p.name not in OPS_SKIP)
    scan: list[tuple[Note, Path]] = []
    for p in candidates:
        if not p.exists():
            continue
        r = rel(p)
        group = next((g for g in OPS_GROUPS if r.startswith(g)), None)
        if group:
            gname = group.rstrip("/").replace("/", ".") + " (folder)"
            if gname not in notes:
                notes[gname] = Note(name=gname, layer="ops", kind="folder", key=f"ops:{group}", source=group,
                                    summary=OPS_GROUPS[group])
                scan.append((notes[gname], ROOT / group))
            g = notes[gname]
            g.sections["Files"].append(f"`{r}`")
            g.lines += p.read_text(encoding="utf-8", errors="replace").count("\n") + 1
            if p.suffix == ".md":
                scan.append((g, p))
            continue
        name = ops_note_name(r)
        n = Note(name=name, layer="ops", kind="ops", key=f"ops:{r}", source=r)
        text = p.read_text(encoding="utf-8", errors="replace")
        n.lines = text.count("\n") + 1
        if p.suffix == ".md":
            prose = re.sub(r"^(```|~~~).*?^\1", "", text, flags=re.M | re.S)  # drop fenced code
            heads = re.findall(r"^#{1,2}\s+(.+)$", prose, re.M)
            n.summary = "Markdown outside the vault; its top headings are listed below."
            n.sections["Headings"] = [h.strip() for h in heads[:40]]
        else:
            m = re.match(r"\s*(?:#|::|REM|<#|//)\s*(.+)", text)
            if m and not m.group(1).startswith("!"):
                n.summary = m.group(1).strip()[:300]
        scan.append((n, p))
        notes[name] = n
    return scan


