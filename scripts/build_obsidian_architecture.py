@dataclass
class Note:
    name: str
    layer: str  # backend | frontend | db | ops
    kind: str  # module | router | table | migration | page | component | lib | hook | folder | ops | file
    key: str  # matched against HUB_RULES
    source: str  # repo-relative path
    summary: str = ""
    facts: list[str] = field(default_factory=list)
    sections: dict[str, list[str]] = field(default_factory=lambda: defaultdict(list))
    links: dict[str, set[str]] = field(default_factory=lambda: defaultdict(set))
    lines: int = 0

    def link(self, section: str, target: str) -> None:
        if target and target != self.name:
            self.links[section].add(target)


def rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def first_paragraph(text: str | None, limit: int = 400) -> str:
    if not text:
        return ""
    para = text.strip().split("\n\n")[0]
    para = " ".join(line.strip() for line in para.splitlines())
    return para[: limit - 1] + "…" if len(para) > limit else para


def safe_text(s: str) -> str:
    for pat in SECRET_PATTERNS:
        s = pat.sub("[redacted]", s)
    return s


